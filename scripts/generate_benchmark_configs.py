#!/usr/bin/env python
"""Expand configs/benchmark/{suite,arms}.yaml into runnable ExperimentConfigs.

    python scripts/generate_benchmark_configs.py                 # write + manifest
    python scripts/generate_benchmark_configs.py --dry-run       # just count
    python scripts/generate_benchmark_configs.py --imagenet-root /n/...
    python scripts/generate_benchmark_configs.py --only mash --models cifar10_resnet20

One config per (suite entry x arm), written to
`configs/benchmark/generated/<entry>/<arm>.yaml`, plus `manifest.txt` listing
them one per line -- which is what the SLURM array indexes into.

Combinations a method would refuse are skipped rather than emitted and left to
fail in the queue: `requires: fc` arms are dropped on conv entries, and the
MASH grid's closed-form repairs (kernel/projection) are dropped there too. The
skip reasons are printed, so a shrinking count is visible rather than silent.

Generated files are disposable -- regenerate after editing suite.yaml or
arms.yaml. They are deliberately NOT gitignored: the exact configs a table was
produced from are part of the record.
"""

from __future__ import annotations

import argparse
import itertools
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

BENCH = ROOT / "configs" / "benchmark"
OUT = BENCH / "generated"
PLACEHOLDER = "PLACEHOLDER_IMAGENET_ROOT"   # none left in suite.yaml; kept for overrides


# ── arm expansion ────────────────────────────────────────────────────────────

def expand_arms(arms_spec: dict) -> list[dict]:
    """[{name, kind, params, requires, tier}] from the explicit arms plus grids.

    `tier` is 'headline' for names listed under arms.yaml's `headline:` key and
    'ablation' otherwise. Headline is a SUBSET of all, so a tier of 'all' runs
    both.
    """
    out: list[dict] = []
    for a in arms_spec.get("arms", []) or []:
        out.append({"name": a["name"], "kind": a["kind"],
                    "params": dict(a.get("params") or {}),
                    "requires": a.get("requires")})

    for g in arms_spec.get("grids", []) or []:
        axes = g.get("axes") or {}
        keys = sorted(axes)
        fixed = dict(g.get("fixed") or {})
        fc_when = g.get("requires_fc_when") or {}
        nobn_when = g.get("requires_nobn_when") or {}
        for combo in itertools.product(*(axes[k] for k in keys)):
            params = dict(fixed)
            params.update(dict(zip(keys, combo)))
            # name from the axes only, so `fixed` stays in the prefix
            tag = "_".join(str(params[k]) for k in keys)
            requires = g.get("requires")
            for pk, bad in fc_when.items():
                if params.get(pk) in bad:
                    requires = "fc"
            needs_nobn = any(params.get(pk) in bad
                             for pk, bad in nobn_when.items())
            out.append({"name": f"{g['prefix']}_{tag}", "kind": g["kind"],
                        "params": params, "requires": requires,
                        "requires_nobn": needs_nobn})

    headline = set(arms_spec.get("headline") or [])
    seen: dict[str, dict] = {}
    for a in out:
        if a["name"] in seen:
            raise ValueError(f"duplicate arm name {a['name']!r}")
        a["tier"] = "headline" if a["name"] in headline else "ablation"
        seen[a["name"]] = a
    unknown = headline - set(seen)
    if unknown:
        raise ValueError(f"arms.yaml headline names no such arm(s): {sorted(unknown)}")
    return out


# ── config assembly ──────────────────────────────────────────────────────────

def build_config(entry: dict, arm: dict, defaults: dict,
                 seeds: list[int], imagenet_root: str | None) -> dict:
    data = {"kind": entry["data"]["kind"],
            "params": dict(entry["data"].get("params") or {})}
    if "root" in data["params"]:
        if data["params"]["root"] == PLACEHOLDER and not imagenet_root:
            raise ValueError(
                f"{entry['name']} needs --imagenet-root (its data.params.root is "
                f"still {PLACEHOLDER})")
        if imagenet_root:
            data["params"]["root"] = imagenet_root

    trains = bool(entry.get("train"))
    training = (dict(entry.get("training") or {}) if trains
                else dict(defaults.get("training_pretrained") or {"epochs": 0}))

    note = (f"Benchmark cell: {entry['name']} x {arm['name']}. "
            + ("Trained here (no published checkpoint). "
               if trains else "Pretrained weights downloaded; no training. ")
            + "Generated by scripts/generate_benchmark_configs.py -- edit "
              "configs/benchmark/{suite,arms}.yaml, not this file.")

    return {
        "name": f"{entry['name']}__{arm['name']}",
        "notes": note,
        "data": data,
        "model": {"kind": entry["model"]["kind"],
                  "params": dict(entry["model"].get("params") or {})},
        "training": training,
        "pruning": {"methods": [{"kind": arm["kind"],
                                 "params": dict(arm["params"])}]},
        "finetune": dict(defaults.get("finetune") or {"epochs": 0}),
        "seeds": list(seeds),
        "output_root": defaults.get("output_root", "outputs/benchmark"),
        # HEADLINE ARMS ONLY. The geometry and similarity batteries are
        # exploratory and quadratic in layer width -- the K matrix alone is
        # 3072x3072 per layer on OPT-125m -- and they dominated the smoke test
        # completely: 1136s of a 1224s seed, against 9s for the width sweep that
        # is the actual measurement. Running them on all 50 ablation arms buys
        # nothing, since what we read is a few representative arms. A suite entry
        # or the defaults block can still force either way.
        "analyze_geometry": bool(
            entry.get("analyze_geometry",
                      defaults.get("analyze_geometry",
                                  arm.get("tier") == "headline"))),
        "deterministic": bool(defaults.get("deterministic", True)),
        # A downloaded checkpoint saw the whole official train split, so the val
        # slice carved from it is training data to that model. Grade it on test.
        "eval_split": entry.get("eval_split", "val" if trains else "test"),
        **({"require_accuracy": entry["require_accuracy"]}
           if entry.get("require_accuracy") is not None else {}),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--imagenet-root", default=None,
                    help="override the ImageNet path baked into suite.yaml")
    ap.add_argument("--only", nargs="*", default=None,
                    help="keep arms whose name starts with any of these")
    ap.add_argument("--models", nargs="*", default=None,
                    help="keep only these suite entries (by name)")
    ap.add_argument("--resources", nargs="*", default=None,
                    help="keep only these resource classes")
    ap.add_argument("--tier", choices=("headline", "ablation", "all"), default=None,
                    help="override every entry's arms_tier (default: per-entry)")
    ap.add_argument("--output-root", default=None,
                    help="where results go (default: suite.yaml's, i.e. lab scratch)")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--clean", action="store_true",
                    help="delete generated/ before writing")
    args = ap.parse_args()

    suite = yaml.safe_load((BENCH / "suite.yaml").read_text())
    arms = expand_arms(yaml.safe_load((BENCH / "arms.yaml").read_text()))
    defaults = suite.get("defaults") or {}
    if args.output_root:
        defaults["output_root"] = args.output_root
    overrides = suite.get("seed_overrides") or {}

    entries = suite["entries"]
    if args.models:
        entries = [e for e in entries if e["name"] in set(args.models)]
    if args.resources:
        entries = [e for e in entries if e.get("resources") in set(args.resources)]
    if args.only:
        arms = [a for a in arms
                if any(a["name"].startswith(p) for p in args.only)]

    if args.clean and OUT.exists() and not args.dry_run:
        shutil.rmtree(OUT)

    manifest: list[str] = []
    by_class: dict[str, list[str]] = {}
    skipped: dict[str, int] = {}
    per_entry: list[tuple[str, int, str]] = []
    missing_root: list[str] = []

    default_tier = defaults.get("arms_tier", "headline")
    for entry in entries:
        kept = 0
        tier = args.tier or entry.get("arms_tier", default_tier)
        for arm in arms:
            if tier == "headline" and arm["tier"] != "headline":
                continue
            if tier == "ablation" and arm["tier"] == "headline":
                continue
            if arm["name"] in (entry.get("exclude_arms") or ()):
                # Measured, not guessed: HOPE's pair enumeration scales H^2.28,
                # so a 3072-wide OPT layer costs ~1583s to plan and its 12
                # layers ~5h PER SEED for one arm -- after a 20x speedup. That
                # cost is intrinsic (a rank-2 solve per pair, unlike Ward's
                # Lance-Williams update), so the honest move is to declare the
                # arm unrun at that width rather than spend 90 GPU-hours on it.
                # hope_prune_only stays: allow_merge=false enumerates nothing.
                continue
            fam = entry.get("family")
            if arm.get("requires_nobn") and entry.get("bn"):
                # The layer's paired BatchNorm makes a synthesized hyperplane
                # unwritable -- see requires_nobn_when in arms.yaml.
                continue
            if arm.get("requires") == "fc" and fam != "fc":
                # `mixed` (LeNet: conv slots AND fc slots) is treated like conv:
                # an fc-only arm would raise on the conv slots, and prune_model
                # applies one method to every layer. Conservative on purpose.
                key = f"{arm['name']} (fc-only) on {fam}"
                skipped[key] = skipped.get(key, 0) + 1
                continue
            seeds = overrides.get(entry["name"], defaults.get("seeds", [0]))
            try:
                cfg = build_config(entry, arm, defaults, seeds, args.imagenet_root)
            except ValueError as exc:
                if entry["name"] not in missing_root:
                    missing_root.append(entry["name"])
                    print(f"  SKIP {entry['name']}: {exc}")
                break
            rel = Path(entry["name"]) / f"{arm['name']}.yaml"
            rec = str(Path("configs/benchmark/generated") / rel)
            manifest.append(rec)
            cls = entry.get("resources", "small")
            by_class.setdefault(cls, []).append(rec)
            by_class.setdefault(f"{cls}_{arm['tier']}", []).append(rec)
            kept += 1
            if not args.dry_run:
                path = OUT / rel
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(yaml.safe_dump(cfg, sort_keys=False, width=100))
        per_entry.append((entry["name"], kept, entry.get("resources", "?"), tier))

    print(f"\n{len(arms)} arms x {len(entries)} entries")
    print(f"{'entry':<26}{'configs':>9}{'resources':>11}{'tier':>11}")
    for name, n, res, tier in per_entry:
        print(f"  {name:<24}{n:>9}{res:>11}{tier:>11}")
    total_jobs = sum(
        n * len(overrides.get(name, defaults.get("seeds", [0])))
        for name, n, _, _ in per_entry)
    print(f"\n{len(manifest)} configs  ->  {total_jobs} (config x seed) runs")
    if skipped:
        print("\nskipped (method would refuse):")
        for reason, n in sorted(skipped.items(), key=lambda kv: -kv[1])[:12]:
            print(f"  {n:>4}x  {reason}")

    if not args.dry_run:
        (BENCH / "manifest.txt").write_text("\n".join(manifest) + "\n")
        # One manifest per resource class: #SBATCH lines are parsed before the
        # script runs, so a single array cannot carry per-entry memory/time.
        # Submit one array per class instead (scripts/submit_benchmark.sh).
        for cls, rows in sorted(by_class.items()):
            (BENCH / f"manifest_{cls}.txt").write_text("\n".join(rows) + "\n")
        print(f"\nwrote {OUT}")
        print(f"wrote {BENCH / 'manifest.txt'} ({len(manifest)} lines)")
        base = {c: r for c, r in by_class.items()
                if not c.endswith(("_headline", "_ablation"))}
        print("\ncells per class:")
        for cls in sorted(base):
            h = len(by_class.get(f"{cls}_headline", []))
            a = len(by_class.get(f"{cls}_ablation", []))
            print(f"  {cls:<8}{len(base[cls]):>5} total  ({h} headline, {a} ablation)")
        print("\nstaged submission -- headline first populates Tables 2/3:")
        print("  bash scripts/submit_benchmark.sh --tier headline")
        print("  bash scripts/submit_benchmark.sh --tier ablation")
        print("  bash scripts/submit_benchmark.sh                  # everything")


if __name__ == "__main__":
    main()
